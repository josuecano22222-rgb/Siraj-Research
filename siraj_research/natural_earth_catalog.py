# Nominal scale + detail tier per Natural Earth vector scale.
SCALES = {
    "110m": {"nominal": "1:110 million", "detail": "low", "zoom_tier": 0},
    "50m": {"nominal": "1:50 million", "detail": "medium", "zoom_tier": 1},
    "10m": {"nominal": "1:10 million", "detail": "high", "zoom_tier": 2},
}

# Zoom bands that select the scale tier automatically on the client.
ZOOM_TIERS = [
    {"max_zoom": 3.99, "scale": "110m"},
    {"max_zoom": 6.99, "scale": "50m"},
    {"max_zoom": 99,    "scale": "10m"},
]

def scale_for_zoom(zoom: float) -> str:
    """Return the Natural Earth scale tier appropriate for a map zoom level.

    World-scale views use the coarse 1:110m tier, mid-zoom the 1:50m tier
    and detailed views the 1:10m tier. The client falls back to the finest
    *available* tier when a higher tier has not been provisioned.
    """
    for tier in ZOOM_TIERS:
        if zoom <= tier["max_zoom"]:
            return tier["scale"]
    return "10m"

def scale_order():
    return ["110m", "50m", "10m"]

