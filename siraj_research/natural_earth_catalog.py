"""Natural Earth Layer catalog — authoritative metadata for the
full public-domain Natural Earth vector dataset (https://github.com/nvkelso/natural-earth-vector).

The catalog covers every GeoJSON layer published by Natural Earth across the
three vector scales:

    - 110m (1:110 million) — 32 layers, ~20 MB — BUNDLED in this app for
      instant offline basemap use.
    - 50m (1:50 million)  — 45 layers, ~60 MB — provisioned into private
      storage by the Natural Earth Vector Pack admin tool.
    - 10m (1:10 million)  — 129 layers, ~1.1 GB — provisioned the same way.

Each entry describes one ``ne_<scale>_<layer>.geojson`` file: its scale, the
Natural Earth category (cultural / physical), a rendering kind, a short
human-readable description and the byte size of the source file. Catalog
keys are the full GeoJSON file names (identical to the file names on disk
and the ``layer`` API parameter).

Data provenance: Natural Earth 5.2.0-pre, public domain (see
``public/natural_earth/LICENSE.md``). The dataset is unmodified; layer
geometries and properties are served exactly as published.
"""
